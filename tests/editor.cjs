const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {});
  try {
    const page = await browser.newPage(); page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', err => errors.push(err.message));
    let dispatch;
    await page.route('https://raw.githubusercontent.com/**', route => route.abort());
    await page.route('https://api.github.com/**', async route => { dispatch = route.request().postDataJSON(); await route.fulfill({ status: 204 }); });
    await page.goto('file://' + path.resolve('docs/index.html'), { waitUntil: 'domcontentloaded' });
    await page.evaluate(() => localStorage.clear()); await page.reload({ waitUntil: 'domcontentloaded' });
    await page.locator('#preset').selectOption('builtin:In a meeting');
    assert.equal(await page.locator('#message').inputValue(), 'IN A\nMEETING');
    await page.locator('#message').fill('CUSTOM <MESSAGE>');
    await page.locator('#subline').fill('Back at 3:45 PM');
    await page.locator('#note').fill('Email me & I’ll reply');
    await page.locator('#theme').selectOption('dark');
    await page.locator('#preset-name').fill('Afternoon'); await page.locator('#save-preset').click();
    await page.reload({ waitUntil: 'domcontentloaded' });
    assert.equal(await page.locator('#message').inputValue(), 'CUSTOM <MESSAGE>');
    await page.locator('#preset').selectOption('saved:Afternoon');
    await page.locator('#send-custom').click(); assert.match(await page.locator('#editor-status').textContent(), /Unlock/);
    await page.locator('#username').fill('Test'); await page.locator('#token').fill('fake-test-token'); await page.locator('#unlock').click();
    await page.locator('#send-custom').click();
    await page.waitForFunction(() => !document.getElementById('send-custom').disabled);
    assert.deepEqual(Object.keys(dispatch.inputs), ['status_json']); assert.equal(JSON.parse(dispatch.inputs.status_json).subline, 'Back at 3:45 PM');
    assert.match(await page.locator('#editor-status').textContent(), /queued/);
    await page.route('https://api.github.com/**', route => route.fulfill({ status: 403, body: '{}' }));
    await page.locator('#send-custom').click(); await page.waitForFunction(() => !document.getElementById('send-custom').disabled); assert.match(await page.locator('#editor-status').textContent(), /403/);
    assert.equal(await page.locator('#send-custom').isEnabled(), true);
    await page.unroute('https://api.github.com/**');
    await page.route('https://api.github.com/**', route => route.abort());
    await page.locator('#send-custom').click(); await page.waitForFunction(() => !document.getElementById('send-custom').disabled); assert.ok(await page.locator('#send-custom').isEnabled());
    await page.locator('#lock').click(); assert.equal(await page.evaluate(() => localStorage.getItem('trmnl_picker_token')), null);
    const download = page.waitForEvent('download', { timeout: 10000 }); await page.locator('#download-status').click(); assert.equal((await download).suggestedFilename(), 'office-status.png');
    await page.locator('#delete-preset').click(); assert.equal(await page.locator('#preset option[value="saved:Afternoon"]').count(), 0);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('#message').fill('A'.repeat(100)); await page.locator('#subline').fill('Long subline '.repeat(8));
    const normalized = await page.evaluate(() => StatusRenderer.normalize({ contacts: ['Email', 'Email', 'evil'], theme: 'other' }));
    assert.deepEqual(normalized.contacts, ['Email']); assert.equal(normalized.theme, 'light');
    await page.setViewportSize({ width: 1280, height: 1000 });
    await page.locator('#preset').selectOption('builtin:In the office');
    const pixels = await page.evaluate(() => { const ctx = document.getElementById('status-preview').getContext('2d'); return { top: [...ctx.getImageData(2, 100, 1, 1).data], footer: [...ctx.getImageData(2, 360, 1, 1).data] }; });
    assert.deepEqual(pixels.top, [255, 255, 255, 255]); assert.deepEqual(pixels.footer, [0, 0, 0, 255]);
    if (process.env.SCREENSHOT) await page.locator('[aria-labelledby=editor-heading]').screenshot({ path: process.env.SCREENSHOT });
    assert.deepEqual(errors, []);
    console.log('Browser checks passed: presets, persistence, preview, download, dispatch, errors, lock, and mobile layout.');
  } finally { await browser.close(); }
})().catch(err => { console.error(err); process.exit(1); });
